-- Behy Messenger Database
-- Initial database schema

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique,
  display_name text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  receiver_id uuid not null references public.profiles(id) on delete cascade,
  content text not null check (
    char_length(trim(content)) between 1 and 5000
  ),
  created_at timestamptz not null default now()
);

create index if not exists messages_sender_idx
on public.messages(sender_id, created_at);

create index if not exists messages_receiver_idx
on public.messages(receiver_id, created_at);

create index if not exists profiles_username_idx
on public.profiles(username);

alter table public.profiles enable row level security;
alter table public.messages enable row level security;

-- Profiles policies
drop policy if exists "Authenticated users can view profiles"
on public.profiles;

create policy "Authenticated users can view profiles"
on public.profiles
for select
to authenticated
using (true);

drop policy if exists "Users can create their own profile"
on public.profiles;

create policy "Users can create their own profile"
on public.profiles
for insert
to authenticated
with check (auth.uid() = id);

drop policy if exists "Users can update their own profile"
on public.profiles;

create policy "Users can update their own profile"
on public.profiles
for update
to authenticated
using (auth.uid() = id)
with check (auth.uid() = id);

-- Messages policies
drop policy if exists "Users can view their own conversations"
on public.messages;

create policy "Users can view their own conversations"
on public.messages
for select
to authenticated
using (
  auth.uid() = sender_id
  or auth.uid() = receiver_id
);

drop policy if exists "Users can send messages as themselves"
on public.messages;

create policy "Users can send messages as themselves"
on public.messages
for insert
to authenticated
with check (
  auth.uid() = sender_id
  and sender_id <> receiver_id
);

-- Enable realtime messages
do $$
begin
  alter publication supabase_realtime
  add table public.messages;
exception
  when duplicate_object then null;
  when undefined_object then null;
end $$;
